		foreach ( preg_split( '/\R/u', trim( $data ) ) as $index => $line ) {
			$parts = explode( '|', $line, 2 );
			if ( 2 !== count( $parts ) ) {
				continue;
			}
			$key                 = sprintf( 'occupation_%03d', $index + 1 );
			$occupations[ $key ] = trim( $parts[1] );
		}

		// Keep the source catalog stable while making the fallback choice explicit.
		$occupations['other'] = 'سایر';
		$other = $occupations['other'];
		unset( $occupations['other'] );
		if ( class_exists( 'Collator' ) ) {
			$collator = new Collator( 'fa_IR' );
			uasort( $occupations, function ( $left, $right ) use ( $collator ) { return $collator->compare( $left, $right ); } );
		} else {
			uasort( $occupations, function ( $left, $right ) { return strcmp( $left, $right ); } );
		}
		$occupations['other'] = $other;

		return $occupations;
	}

