	public static function provinces() {
		$out = array();
		foreach ( self::iran_geography() as $key => $province ) { $out[ $key ] = $province['label']; }
		return $out;
	}

	public static function cities() {
		$out = array();
		foreach ( self::iran_geography() as $province_key => $province ) {
			foreach ( $province['cities'] as $city_key => $label ) { $out[ $city_key ] = $label; }
		}
		return $out;
	}

	public static function cities_for_province( $province_key ) {
		$province_key = sanitize_key( $province_key );
		$geography    = self::iran_geography();
		return isset( $geography[ $province_key ]['cities'] ) ? $geography[ $province_key ]['cities'] : array();
	}

	public static function city_province_map() {
		$out = array();
		foreach ( self::iran_geography() as $province_key => $province ) {
			foreach ( $province['cities'] as $city_key => $label ) { $out[ $city_key ] = $province_key; }
		}
		return $out;
	}

